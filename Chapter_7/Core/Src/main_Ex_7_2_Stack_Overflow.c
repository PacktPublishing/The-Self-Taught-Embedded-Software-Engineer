/**
 ******************************************************************************
 * @file    main_Ex_7_2_Stack_Overflow.c
 * @author  Renato Soriano
 * @brief   Chapter 7 - Exercise 7.2: measure the stack, then overflow it on
 *          purpose and watch nothing complain   [SWV ITM build]
 *
 * @target  STM32F446RE - Nucleo-F446RE (ARM Cortex-M4)
 * @output  SWV ITM Data Console, Stimulus Port 0, core clock 16000000 Hz
 *
 * @details Four phases, each printed as it runs:
 *
 *          1. Measure. Paint the reserved stack, run an ordinary workload
 *             (a short call chain with a few locals and a printf), and read
 *             the high-water mark. This is the number to size the reserve
 *             against, measured rather than guessed.
 *
 *          2. Fill the heap. Ask malloc() for the largest block it will give.
 *             The C library's _sbrk() (sysmem.c, generated by STM32CubeIDE)
 *             lets the heap grow until it would cross into the reserved stack,
 *             so the block ends just below the stack limit. _Min_Heap_Size
 *             turns out to be a minimum the linker guarantees, not a maximum
 *             anything enforces.
 *
 *          3. Overflow. Call a function whose local array is larger than the
 *             whole reserved stack. Its frame runs off the bottom of the
 *             reserve and over the end of the heap block.
 *
 *          4. Inspect. Check the canary at the bottom of the reserve and count
 *             how many bytes of the heap block were overwritten. The program
 *             is still running normally. There was no fault, no reset, and no
 *             warning. That silence is the lesson.
 *
 *          Then halt the debugger and look at the damage yourself: the
 *          addresses to type into the Memory Browser are printed at the end.
 *
 *          Deliberate MISRA departures, both for this demonstration only:
 *          Rule 21.3 (malloc), because the heap is the subject, and a stack
 *          frame known to exceed its reserve, because the overflow is the
 *          subject. Neither belongs in production firmware.
 *
 *          SRAM after phase 2, low addresses at the bottom:
 *
 *              0x20020000  _estack ---------------------------------- top
 *                          stack in use by main(), growing down
 *                          painted, unused stack
 *              0x2001FC00  canary = bottom of the 1 KB reserve
 *                          a few bytes the heap could not use
 *                          heap block, filled with 0xA5 (about 126 KB)
 *              _end        heap start
 *                          .bss, .data
 *              0x20000000  ------------------------------------------ bottom
 *
 *          Phase 3 pushes the stack about 1.6 KB below _estack: the 1536-byte
 *          array on top of what main() already uses. That is nearly 600
 *          bytes past the bottom of the 1 KB reserve, through the canary and
 *          into the top of the heap block (on the board the array starts at
 *          0x2001F9B4, 588 bytes below the canary). Nothing in between stops
 *          it: the boundaries in this diagram exist only as numbers in the
 *          linker script.
 ******************************************************************************
 */

#include "main.h"
#include "itm_debug.h"
#include "stack_monitor.h"
#include <stdio.h>
#include <stdint.h>
#include <stdlib.h>

#if !defined(__SOFT_FP__) && defined(__ARM_FP)
  #warning "FPU is not initialized, but the project is compiling for an FPU. Please initialize the FPU before use."
#endif

extern uint32_t _end;             /* heap start, from the linker script      */
extern uint32_t _Min_Heap_Size;

/* Bigger than the whole 1 KB reserve, so the overflow is certain. Lower it
 * until it plus the stack main() already uses (printed in phase 3) fits in
 * the reserve, and the same code runs without damaging anything. */
#define STACK_HOG_BYTES      (1536U)

/* Heap search and fill settings:
 *   HEAP_FILL         byte written over the whole heap block. A byte that no
 *                     longer reads 0xA5 afterwards was written by something
 *                     else, which is how phase 4 finds the damage.
 *   HEAP_SEARCH_STEP  how much smaller each retry of malloc() asks for.
 *                     16 bytes is fine-grained enough to land within a few
 *                     bytes of the true maximum.
 *   HEAP_SEARCH_SPAN  give up after asking for 1 KB less than the gap; if
 *                     that still fails, something else is wrong. */
#define HEAP_FILL            (0xA5U)
#define HEAP_SEARCH_STEP     (16U)
#define HEAP_SEARCH_SPAN     (1024U)  /* how far below the limit to keep trying */

/* Incremented forever by the final loop, so a debugger can see the program
 * is still running normally after the overflow. volatile keeps the
 * increments from being optimized away. */
static volatile uint32_t s_alive = 0U;

/* ---- Phase 1 workload: an ordinary, well-behaved call chain ------------ */

/* =========================================================================
 * leaf_checksum
 *
 * The bottom of the phase 1 call chain: a shift-and-XOR checksum over a
 * buffer. The value itself is unimportant; it is printed so the compiler
 * cannot discard the work, and so the call chain really goes three deep
 * (main -> middle_layer -> leaf_checksum, then printf).
 * ========================================================================= */
static uint32_t leaf_checksum(const uint8_t *p, uint32_t n)
{
    uint32_t sum = 0U;
    for (uint32_t i = 0U; i < n; i++)
    {
        sum = (sum << 1) ^ p[i];
    }
    return sum;
}

/* =========================================================================
 * middle_layer
 *
 * A typical function: a 64-byte local buffer, a call to a helper, and a
 * printf. With seed 7 the checksum is always 0x83846C44, a quick sign the
 * build is the expected one.
 *
 * Most of the phase 1 peak comes from printf(), not from the 64-byte
 * buffer: formatted output is one of the deepest stack users in a typical
 * embedded program, which is worth remembering when sizing a stack.
 * ========================================================================= */
static uint32_t middle_layer(uint32_t seed)
{
    uint8_t frame[64];                /* a modest local buffer */
    for (uint32_t i = 0U; i < sizeof(frame); i++)
    {
        frame[i] = (uint8_t)(seed + i);
    }
    printf("  workload checksum 0x%08lX\r\n",
           (unsigned long)leaf_checksum(frame, sizeof(frame)));
    return frame[0];
}

/* ---- Phase 3: a frame that cannot fit ----------------------------------
 * noinline keeps the array in this function's own frame, below main()'s,
 * instead of letting the optimizer merge it into main(). volatile keeps
 * every store, so the writes really land in memory. */

/* =========================================================================
 * stack_hog
 *
 * Reserves a 1536-byte local array, 512 bytes more than the entire reserve,
 * and writes every byte of it: scratch[i] = i, so the bytes read 00 01 02 03
 * ... upward from the lowest address. The frame starts below main()'s, so
 * scratch[0] lands deepest, inside the heap block, and the counting pattern
 * is easy to recognize in the Memory Browser.
 *
 * Returns scratch[0] + scratch[1535] = 0 + 255 = 255. Printing it proves
 * the function ran to the end and returned normally, overflow and all.
 * ========================================================================= */
static __attribute__((noinline)) uint32_t stack_hog(void)
{
    volatile uint8_t scratch[STACK_HOG_BYTES];

    for (uint32_t i = 0U; i < STACK_HOG_BYTES; i++)
    {
        scratch[i] = (uint8_t)i;      /* wraps every 256 bytes: 00..FF, 00.. */
    }
    return (uint32_t)scratch[0] + (uint32_t)scratch[STACK_HOG_BYTES - 1U];
}

/* ---- Phase 2: take the largest heap block malloc() will hand out ------- */

/* =========================================================================
 * grab_heap
 *
 * Finds and allocates the largest block malloc() will give, and returns it
 * with its size in *size_out (NULL and 0 if none was found).
 *
 * It starts by asking for the whole gap between the heap start (_end) and
 * the stack limit. That always fails, because malloc() needs a few bytes of
 * its own bookkeeping on top of what you ask for. So it retries 16 bytes
 * smaller each time until one succeeds. On the board this lands about 8
 * bytes below the stack limit: the heap really does reach right up to the
 * stack, whatever _Min_Heap_Size says.
 * ========================================================================= */
static uint8_t *grab_heap(uint32_t *size_out)
{
    const uint32_t heap_start = (uint32_t)&_end;
    const uint32_t ceiling    = stack_limit_address();
    uint32_t size = ceiling - heap_start;
    uint8_t *block = NULL;

    /* A failed malloc() moves nothing, so stepping down costs no memory. */
    while ((block == NULL) && (size > (ceiling - heap_start - HEAP_SEARCH_SPAN)))
    {
        block = (uint8_t *)malloc(size);
        if (block == NULL)
        {
            size -= HEAP_SEARCH_STEP;
        }
    }
    *size_out = (block != NULL) ? size : 0U;
    return block;
}

/* =========================================================================
 * main
 *
 * Runs the four phases once, prints where to look in the Memory Browser,
 * then spins forever to show the program is still alive. The block comment
 * at the top of the file describes each phase.
 * ========================================================================= */
int main(void)
{
    /* Unbuffered stdout. Besides making ITM output immediate, this keeps the
     * C library from allocating a stdout buffer with malloc(), so the heap is
     * still empty when phase 2 measures it. */
    setvbuf(stdout, NULL, _IONBF, 0);   /* unbuffered: stdout takes no heap   */

    /* Paint first, while almost nothing has used the stack yet. */
    stack_paint();

    printf("\r\nChapter 7 - Exercise 7.2: stack sizing and a deliberate overflow\r\n");
    printf("stack top 0x%08lX, limit 0x%08lX, %lu bytes reserved\r\n",
           (unsigned long)stack_top_address(), (unsigned long)stack_limit_address(),
           (unsigned long)stack_reserved_bytes());

    /* Phase 1 -----------------------------------------------------------
     * Run the workload, then read how deep the stack went. The figure is a
     * floor for sizing the reserve, not the size itself: painting only sees
     * stack that was written, and a real program has paths this test did
     * not take. */
    printf("\r\n[1] measure: run a normal workload, then read the high-water mark\r\n");
    (void)middle_layer(7U);
    const uint32_t peak_normal = stack_peak_bytes();
    printf("  peak stack use %lu of %lu bytes (%lu%%)\r\n",
           (unsigned long)peak_normal, (unsigned long)stack_reserved_bytes(),
           (unsigned long)((peak_normal * 100U) / stack_reserved_bytes()));

    /* Phase 2 -----------------------------------------------------------
     * Take the whole heap, then fill it with a known byte so any later write
     * into it shows up. The fill also touches every byte, proving the block
     * is real memory and not just a number malloc() returned. */
    printf("\r\n[2] heap: ask malloc() for the largest block it will give\r\n");
    uint32_t block_size = 0U;
    uint8_t *block = grab_heap(&block_size);
    if (block == NULL)
    {
        printf("  malloc() refused every size tried; nothing to demonstrate\r\n");
        Error_Handler();
    }
    for (uint32_t i = 0U; i < block_size; i++)
    {
        block[i] = HEAP_FILL;
    }
    const uint32_t block_end = (uint32_t)block + block_size;
    /* &_Min_Heap_Size is the linker's minimum (512). The block is about 250
     * times larger: nothing at run time holds the heap to that figure. */
    printf("  block 0x%08lX to 0x%08lX, %lu bytes (_Min_Heap_Size is only %lu)\r\n",
           (unsigned long)(uint32_t)block, (unsigned long)block_end,
           (unsigned long)block_size, (unsigned long)(uint32_t)&_Min_Heap_Size);
    printf("  gap between the block and the stack limit: %lu bytes\r\n",
           (unsigned long)(stack_limit_address() - block_end));

    /* Phase 3 -----------------------------------------------------------
     * Show how much stack is already in use, then call the function whose
     * frame cannot fit. In use + 1536 is far more than the 1024 reserved. */
    printf("\r\n[3] overflow: call a function with a %u-byte local array\r\n",
           (unsigned)STACK_HOG_BYTES);
    const uint32_t used_before = stack_used_now_bytes();
    printf("  stack in use before the call: %lu bytes; the array alone needs %u\r\n",
           (unsigned long)used_before, (unsigned)STACK_HOG_BYTES);
    const uint32_t hog_result = stack_hog();

    /* Phase 4 -----------------------------------------------------------
     * The call came back. Now look for the evidence. */
    printf("\r\n[4] inspect: the call returned normally (result %lu)\r\n",
           (unsigned long)hog_result);

    /* Walk the whole heap block and count bytes that are no longer 0xA5,
     * remembering where the first one is. The count is a lower bound: a
     * byte the stack happened to overwrite with 0xA5 itself looks
     * untouched. On the board, 2 of the 580 overwritten bytes did exactly
     * that (scratch[165] and scratch[421] both hold 0xA5), so the program
     * reports 578. */
    uint32_t damaged = 0U;
    uint32_t first_damaged = 0U;
    for (uint32_t i = 0U; i < block_size; i++)
    {
        if (block[i] != HEAP_FILL)
        {
            if (damaged == 0U)
            {
                first_damaged = (uint32_t)&block[i];
            }
            damaged++;
        }
    }

    printf("  canary at 0x%08lX: %s\r\n", (unsigned long)stack_limit_address(),
           (stack_canary_intact() != 0) ? "intact" : "OVERWRITTEN");
    printf("  heap block bytes overwritten by the stack: %lu\r\n", (unsigned long)damaged);
    if (damaged != 0U)
    {
        printf("  damage runs from 0x%08lX up to the end of the block, 0x%08lX\r\n",
               (unsigned long)first_damaged, (unsigned long)block_end);
    }
    printf("  no fault, no reset, no warning: the CPU has no idea this happened\r\n");

    /* Round the first damaged address down to a 16-byte boundary (& ~0xF)
     * so the Memory Browser row starts on a clean address with a little
     * intact 0xA5 fill visible before the damage. */
    printf("\r\nHalt here and open the Memory Browser at 0x%08lX to see the damage.\r\n",
           (unsigned long)((first_damaged != 0U) ? (first_damaged & ~0xFUL) : block_end));

    while (1)
    {
        s_alive++;          /* still running, as far as anyone can tell */
    }
}

/* =========================================================================
 * Error_Handler
 *
 * Reached only if malloc() refused every size in phase 2. Interrupts are
 * disabled so nothing else runs, and the message goes straight to the ITM
 * port without printf().
 * ========================================================================= */
void Error_Handler(void)
{
    __disable_irq();
    itm_send_string("ERROR: trapped in Error_Handler.\r\n");
    while (1)
    {
    }
}
